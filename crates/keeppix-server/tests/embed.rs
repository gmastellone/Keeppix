use axum::body::Body;
use axum::http::{Request, StatusCode};
use keeppix_test_support::assert_security_headers;
use tower::ServiceExt as _;

/// The test only runs when the frontend has been built: in CI, the frontend
/// build precedes the backend build.
fn frontend_built() -> bool {
    std::path::Path::new(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../frontend/dist/index.html"
    ))
    .exists()
}

#[tokio::test]
#[allow(clippy::unwrap_used)]
async fn index_is_served_at_root() {
    if !frontend_built() {
        eprintln!("frontend/dist missing: skipping test");
        return;
    }

    let app = keeppix_server::embed::mount_stateless();
    let response = app
        .oneshot(Request::builder().uri("/").body(Body::empty()).unwrap())
        .await
        .unwrap();

    assert_eq!(response.status(), StatusCode::OK);
    assert_eq!(response.headers().get("cache-control").unwrap(), "no-cache");
    // The SPA fallback serves precisely the document that boots the entire
    // application: if it comes out without security headers, Keeppix's main
    // page runs without CSP in production while `/health` has it (see the
    // comment on `keeppix_api::with_common_layers`).
    assert_security_headers(response.headers());

    // Proves that the embed actually contains the files built by Vite, not
    // an empty body with status 200: an empty embed would silently degrade
    // to "200 with no content" on every path.
    let body = http_body_util::BodyExt::collect(response.into_body())
        .await
        .unwrap()
        .to_bytes();
    let html = String::from_utf8_lossy(&body);
    assert!(
        html.contains("<script"),
        "embedded index.html must contain the bundle generated by Vite"
    );
}

