#[tokio::test]
#[allow(clippy::unwrap_used)]
async fn media_and_dav_paths_never_fall_back_to_index() {
    if !frontend_built() {
        eprintln!("frontend/dist missing: skipping test");
        return;
    }

    let app = keeppix_server::embed::mount_stateless();
    for path in ["/media/thumb/deadbeef", "/dav/foo"] {
        let response = app
            .clone()
            .oneshot(Request::builder().uri(path).body(Body::empty()).unwrap())
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::NOT_FOUND, "{path}");
        assert_eq!(
            response.headers().get("content-type").unwrap(),
            "application/problem+json",
            "{path} must not receive index.html"
        );
    }
}

#[tokio::test]
#[allow(clippy::unwrap_used, clippy::expect_used)]
async fn assets_are_served_as_immutable() {
    if !frontend_built() {
        eprintln!("frontend/dist missing: skipping test");
        return;
    }

    // The exact bundle filename contains a hash generated by Vite on every
    // build and isn't predictable; the only stable thing is the folder.
    let asset_path = std::fs::read_dir(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../frontend/dist/assets"
    ))
    .unwrap()
    .filter_map(Result::ok)
    .find_map(|entry| {
        let name = entry.file_name().into_string().ok()?;
        std::path::Path::new(&name)
            .extension()
            .is_some_and(|ext| ext.eq_ignore_ascii_case("js"))
            .then_some(name)
    })
    .expect("the Vite build produces at least one .js bundle");

    let app = keeppix_server::embed::mount_stateless();
    let response = app
        .oneshot(
            Request::builder()
                .uri(format!("/assets/{asset_path}"))
                .body(Body::empty())
                .unwrap(),
        )
        .await
        .unwrap();

    assert_eq!(response.status(), StatusCode::OK);
    // This is also the counter-proof for the `Cache-Control: private` layer
    // added in `with_common_layers`: it uses `if_not_present`, so the
    // immutable policy set by the handler must survive. With `overriding`
    // this test would fail — and the first bullet of §9.4 (hashed assets
    // never requested twice) would be undone by its own last line.
    assert_eq!(
        response.headers().get("cache-control").unwrap(),
        "public, max-age=31536000, immutable"
    );
}
